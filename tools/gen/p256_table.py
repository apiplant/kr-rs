#!/usr/bin/env python3
"""Generates crates/kr-crypto/src/p256_table.rs: the fixed-base comb table of P-256.

TABLE[w][j] = j * 16^w * G for w in 0..64, j in 0..16, as projective (x, y, z) in Montgomery form
(R = 2^256 mod p), four little-endian u64 limbs per coordinate. Entry j = 0 is the identity
(0 : R : 0). Run: python3 tools/gen/p256_table.py > crates/kr-crypto/src/p256_table.rs
"""
p = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
gx = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296
gy = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5
R = (1 << 256) % p

def add(P, Q):
    if P is None: return Q
    if Q is None: return P
    (x1, y1), (x2, y2) = P, Q
    if x1 == x2:
        if (y1 + y2) % p == 0: return None
        l = (3 * x1 * x1 - 3) * pow(2 * y1, -1, p) % p
    else:
        l = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (l * l - x1 - x2) % p
    return (x3, (l * (x1 - x3) - y1) % p)

def limbs(v):
    return [(v >> (64 * i)) & 0xFFFFFFFFFFFFFFFF for i in range(4)]

def fmt(P):
    if P is None:
        x, y, z = 0, R, 0
    else:
        x, y, z = P[0] * R % p, P[1] * R % p, R
    return "[" + ", ".join("[" + ", ".join("0x%016x" % l for l in limbs(c)) + "]" for c in (x, y, z)) + "]"

print("// Generated by tools/gen/p256_table.py; do not edit. See that file for the layout.")
print("pub(crate) static BASE_TABLE: [[[[u64; 4]; 3]; 16]; 64] = [")
base = (gx, gy)
for w in range(64):
    row, acc = [None], None
    for j in range(1, 16):
        acc = add(acc, base)
        row.append(acc)
    print("    [")
    for e in row:
        print("        " + fmt(e) + ",")
    print("    ],")
    for _ in range(4):
        base = add(base, base)
print("];")
