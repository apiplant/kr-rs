#!/usr/bin/env python3
"""Generates crates/kr-runtime/src/syscalls.rs: syscall name -> number for x86_64 and aarch64,
from the kernel uapi headers of the build machine (/usr/include/asm/unistd_64.h and
asm-generic/unistd.h). Used to read seccomp profiles by name. Run: tools/gen/syscalls.py"""
import re, sys

def parse(path, three_two=False):
    out = {}
    for line in open(path):
        m = re.match(r"#define __NR_(\w+)\s+(\d+)\s*$", line)
        if m and not m.group(1).startswith(("syscalls", "arch_specific")):
            out[m.group(1)] = int(m.group(2))
        m = re.match(r"#define __NR3264_(\w+)\s+(\d+)\s*$", line)
        if m and three_two:
            out[m.group(1)] = int(m.group(2))
    return out

x86 = parse("/usr/include/asm/unistd_64.h")
x86 = {k: v for k, v in x86.items() if v < 0x4000_0000}  # no x32
arm = parse("/usr/include/asm-generic/unistd.h", True)
src = ["// @generated by tools/gen/syscalls.py from the kernel uapi headers; do not edit.",
       "//! Syscall names and numbers for seccomp profiles that name syscalls.", ""]
for name, tbl in (("X86_64", x86), ("AARCH64", arm)):
    src.append(f"pub const {name}: &[(&str, u32)] = &[")
    for k, v in sorted(tbl.items(), key=lambda kv: (kv[1], kv[0])):
        src.append(f'    ("{k}", {v}),')
    src.append("];")
    src.append(f"pub const {name}_MAX: u32 = {max(tbl.values())};")
    src.append("")
open("crates/kr-runtime/src/syscalls.rs", "w").write("\n".join(src))
print(len(x86), max(x86.values()), len(arm), max(arm.values()))
