//! A minimal OpenAPI surface: v3 operations per resource (enough for kubectl's capability
//! probes, so it sends `fieldValidation=Strict` instead of validating client-side) and, for
//! custom resources only, their schemas in v2 (`/openapi/v2` definitions) and v3 (components),
//! built like apiextensions-apiserver's builder so `kubectl explain` works on them. Built-in
//! kinds have no schemas yet (KNOWN_ISSUES #63).

use crate::crd::Custom;

use crate::resources::{self, Resource, RESOURCES};
use alloc::string::String;
use alloc::vec::Vec;
use kr_fmt::json::{self, Value};

fn o(fields: Vec<(&str, Value)>) -> Value {
    Value::Object(fields.into_iter().map(|(k, v)| (k.into(), v)).collect())
}

fn gv_path(group: &str, version: &str) -> String {
    if group.is_empty() { alloc::format!("api/{version}") } else { alloc::format!("apis/{group}/{version}") }
}

/// `/openapi/v3`: index of group-version documents.
pub fn index(extra: &[&'static Resource]) -> String {
    let mut paths = alloc::vec![(String::from("api/v1"), o(alloc::vec![("serverRelativeURL", Value::from("/openapi/v3/api/v1?hash=kr"))]))];
    for (g, v) in resources::group_versions(extra) {
        let p = gv_path(g, v);
        let url = alloc::format!("/openapi/v3/{p}?hash=kr");
        paths.push((p, o(alloc::vec![("serverRelativeURL", Value::String(url))])));
    }
    json::to_string(&o(alloc::vec![("paths", Value::Object(paths))]))
}

fn op(r: &Resource, action: &str) -> Value {
    let param = |name: &str| o(alloc::vec![("name", Value::from(name)), ("in", Value::from("query")), ("schema", o(alloc::vec![("type", Value::from("string"))]))]);
    o(alloc::vec![
        ("operationId", Value::String(alloc::format!("{action}{}", r.kind))),
        ("parameters", Value::Array(alloc::vec![param("fieldValidation"), param("dryRun"), param("fieldManager")])),
        ("responses", o(alloc::vec![("200", o(alloc::vec![("description", Value::from("OK"))]))])),
        ("x-kubernetes-action", Value::from(action)),
        ("x-kubernetes-group-version-kind", o(alloc::vec![("group", Value::from(r.group)), ("version", Value::from(r.version)), ("kind", Value::from(r.kind))])),
    ])
}

/// `/openapi/v3/<gv path>`: operations per resource (no component schemas).
pub fn group_version(extra: &[&'static Resource], custom: &[Custom], path: &str) -> Option<String> {
    let mut paths = Vec::new();
    for r in RESOURCES.iter().chain(extra.iter().copied()).filter(|r| gv_path(r.group, r.version) == path) {
        let base = if r.namespaced { alloc::format!("/{path}/namespaces/{{namespace}}/{}", r.plural) } else { alloc::format!("/{path}/{}", r.plural) };
        paths.push((base.clone(), o(alloc::vec![("post", op(r, "post")), ("get", op(r, "list"))])));
        paths.push((alloc::format!("{base}/{{name}}"), o(alloc::vec![("get", op(r, "get")), ("put", op(r, "put")), ("patch", op(r, "patch")), ("delete", op(r, "delete"))])));
    }
    if paths.is_empty() {
        return None;
    }
    let mut schemas = Vec::new();
    let crds: Vec<&Custom> = custom.iter().filter(|c| gv_path(c.res.group, c.res.version) == path).collect();
    if !crds.is_empty() {
        for (n, d) in meta_definitions(V3_REF) {
            schemas.push((n, d));
        }
        for c in crds {
            schemas.push((definition_name(c), definition(c, V3_REF)));
        }
    }
    Some(json::to_string(&o(alloc::vec![
        ("openapi", Value::from("3.0.0")),
        ("info", o(alloc::vec![("title", Value::from("Kubernetes")), ("version", Value::from("v1.37.0-kr"))])),
        ("paths", Value::Object(paths)),
        ("components", o(alloc::vec![("schemas", Value::Object(schemas))])),
    ])))
}

const V2_REF: &str = "#/definitions/";
const V3_REF: &str = "#/components/schemas/";

/// Generated by `tools/gen_openapi_meta.py` from upstream's swagger.json: ObjectMeta and what it
/// references, plus the apiVersion/kind/metadata properties added to every CRD schema.
const META_JSON: &str = include_str!("openapi_meta.json");

fn meta_doc() -> Value {
    json::parse(META_JSON.as_bytes()).unwrap_or(Value::Null)
}

/// Rewrites `$ref`s from v2 form to `prefix`.
fn rebase(v: &mut Value, prefix: &str) {
    match v {
        Value::Object(f) => {
            for (k, x) in f.iter_mut() {
                if k == "$ref" {
                    if let Some(r) = x.as_str().and_then(|r| r.strip_prefix(V2_REF)) {
                        *x = Value::String(alloc::format!("{prefix}{r}"));
                    }
                } else {
                    rebase(x, prefix);
                }
            }
        }
        Value::Array(a) => a.iter_mut().for_each(|x| rebase(x, prefix)),
        _ => {}
    }
}

fn meta_definitions(prefix: &str) -> Vec<(String, Value)> {
    let mut d = meta_doc();
    rebase(&mut d, prefix);
    match d.get("definitions") {
        Some(Value::Object(f)) => f.clone(),
        _ => Vec::new(),
    }
}

/// kube-openapi's `ToRESTFriendlyName("<group>/<version>/<Kind>")`: the group's domain reversed
/// (`stable.example.com` -> `com.example.stable`), then `.<version>.<Kind>`.
pub fn definition_name(c: &Custom) -> String {
    let g: Vec<&str> = c.res.group.split('.').rev().collect();
    alloc::format!("{}.{}.{}", g.join("."), c.res.version, c.res.kind)
}

/// A custom resource version's schema as upstream publishes it: the CRD's openAPIV3Schema with
/// apiVersion/kind/metadata properties and the group-version-kind extension.
fn definition(c: &Custom, prefix: &str) -> Value {
    let mut d = match &c.schema {
        // A CRD without validation (the root is only `type: object` with unknown fields
        // preserved) is published as an empty object schema, as upstream does for v2.
        Some(Value::Object(f)) if prefix == V2_REF && f.iter().all(|(k, _)| matches!(k.as_str(), "type" | "x-kubernetes-preserve-unknown-fields")) => o(alloc::vec![("type", Value::from("object"))]),
        Some(Value::Object(f)) => Value::Object(f.clone()),
        _ => o(alloc::vec![("type", Value::from("object"))]),
    };
    let mut props = meta_doc().get("props").cloned().unwrap_or(Value::Null);
    if prefix == V3_REF {
        // v3 wraps references that carry a description in allOf, as upstream does.
        if let Some(m) = props.get("metadata").cloned() {
            let r = m.get("$ref").and_then(Value::as_str).unwrap_or("").replace(V2_REF, V3_REF);
            let desc = m.get("description").cloned().unwrap_or(Value::Null);
            props.set("metadata", o(alloc::vec![("allOf", Value::Array(alloc::vec![o(alloc::vec![("$ref", Value::String(r))])])), ("default", o(Vec::new())), ("description", desc)]));
        }
    }
    if let Value::Object(add) = props {
        let mut own = match d.get("properties") {
            Some(Value::Object(f)) => f.clone(),
            _ => Vec::new(),
        };
        for (k, v) in add {
            own.retain(|(x, _)| *x != k);
            own.push((k, v));
        }
        d.set("properties", Value::Object(own));
    }
    let gvk = o(alloc::vec![("group", Value::from(c.res.group)), ("kind", Value::from(c.res.kind)), ("version", Value::from(c.res.version))]);
    d.set("x-kubernetes-group-version-kind", Value::Array(alloc::vec![gvk]));
    d
}

/// `/openapi/v2`: definitions of custom resources (and the meta types they reference); no paths.
pub fn v2(custom: &[Custom]) -> String {
    let mut defs = meta_definitions(V2_REF);
    for c in custom {
        defs.push((definition_name(c), definition(c, V2_REF)));
    }
    json::to_string(&o(alloc::vec![
        ("swagger", Value::from("2.0")),
        ("info", o(alloc::vec![("title", Value::from("Kubernetes")), ("version", Value::from("v1.37.0-kr"))])),
        ("paths", o(Vec::new())),
        ("definitions", Value::Object(defs)),
    ]))
}
