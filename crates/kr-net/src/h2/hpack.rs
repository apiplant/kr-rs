fn read_int(b: &[u8], pos: &mut usize, prefix: u32) -> Result<usize, Error> {
    let first = *b.get(*pos).ok_or(Error::Truncated)?;
    *pos += 1;
    let max = (1u32 << prefix) - 1;
    let mut v = (first as u32) & max;
    if v < max {
        return Ok(v as usize);
    }
    let mut shift = 0u32;
    loop {
        let x = *b.get(*pos).ok_or(Error::Truncated)?;
        *pos += 1;
        if shift > 28 {
            return Err(Error::IntegerOverflow);
        }
        let add = ((x & 0x7f) as u32)
            .checked_shl(shift)
            .filter(|a| a >> shift == (x & 0x7f) as u32)
            .ok_or(Error::IntegerOverflow)?;
        v = v.checked_add(add).ok_or(Error::IntegerOverflow)?;
        if x & 0x80 == 0 {
            return Ok(v as usize);
        }
        shift += 7;
    }
}

fn write_int(out: &mut Vec<u8>, flags: u8, prefix: u32, mut v: usize) {
    let max = (1usize << prefix) - 1;
    if v < max {
        out.push(flags | v as u8);
        return;
    }
    out.push(flags | max as u8);
    v -= max;
    while v >= 128 {
        out.push((v & 0x7f) as u8 | 0x80);
        v >>= 7;
    }
    out.push(v as u8);
}

fn huff_decode(data: &[u8], out: &mut Vec<u8>) -> Result<(), Error> {
    let (mut code, mut len) = (0u32, 0usize);
    for &byte in data {
        for i in (0..8).rev() {
            code = code << 1 | ((byte >> i) & 1) as u32;
            len += 1;
            if len > 30 {
                return Err(Error::BadHuffman);
            }
            let c = H_COUNT[len] as u32;
            if c != 0 && code >= H_FIRST[len] && code - H_FIRST[len] < c {
                let sym = H_SORTED[H_OFF[len] as usize + (code - H_FIRST[len]) as usize];
                if sym == 256 {
                    return Err(Error::BadHuffman);
                }
                out.push(sym as u8);
                code = 0;
                len = 0;
            }
        }
    }
    // Remaining bits must be a strict prefix of EOS (all ones), shorter than 8 bits.
    if len >= 8 || code != (1u32 << len) - 1 {
        return Err(Error::BadHuffman);
    }
    Ok(())
}

fn read_string(b: &[u8], pos: &mut usize) -> Result<Vec<u8>, Error> {
    let huff = *b.get(*pos).ok_or(Error::Truncated)? & 0x80 != 0;
    let n = read_int(b, pos, 7)?;
    let end = pos.checked_add(n).filter(|&e| e <= b.len()).ok_or(Error::Truncated)?;
    let raw = &b[*pos..end];
    *pos = end;
    let mut v = Vec::new();
    if huff {
        huff_decode(raw, &mut v)?;
    } else {
        v.extend_from_slice(raw);
    }
    Ok(v)
}

/// HPACK decoder holding the connection's dynamic table.
pub struct Decoder {
    table: VecDeque<(Vec<u8>, Vec<u8>)>,
    size: usize,
    cur_max: usize,
    max: usize,
}

impl Decoder {
    /// `max_table_size` is the SETTINGS_HEADER_TABLE_SIZE we advertise (default 4096).
    pub fn new(max_table_size: usize) -> Self {
        Decoder { table: VecDeque::new(), size: 0, cur_max: max_table_size, max: max_table_size }
    }

    fn evict(&mut self, limit: usize) {
        while self.size > limit {
            match self.table.pop_back() {
                Some((n, v)) => self.size -= n.len() + v.len() + 32,
                None => break,
            }
        }
    }

    fn insert(&mut self, name: Vec<u8>, value: Vec<u8>) {
        let sz = name.len() + value.len() + 32;
        self.evict(self.cur_max.saturating_sub(sz));
        if sz <= self.cur_max {
            self.size += sz;
            self.table.push_front((name, value));
        }
    }

    fn lookup(&self, idx: usize) -> Result<(&[u8], &[u8]), Error> {
        if idx == 0 {
            return Err(Error::BadIndex);
        }
        if idx <= STATIC.len() {
            return Ok(STATIC[idx - 1]);
        }
        match self.table.get(idx - STATIC.len() - 1) {
            Some((n, v)) => Ok((n, v)),
            None => Err(Error::BadIndex),
        }
    }

    /// Decodes one complete header block (HEADERS + CONTINUATIONs concatenated).
    pub fn decode(&mut self, block: &[u8]) -> Result<Vec<(Vec<u8>, Vec<u8>)>, Error> {
        let mut out = Vec::new();
        let mut total = 0usize;
        let mut pos = 0;
        let mut fields = false;
        while pos < block.len() {
            let b = block[pos];
            let (name, value, add);
            if b & 0x80 != 0 {
                let idx = read_int(block, &mut pos, 7)?;
                let (n, v) = self.lookup(idx)?;
                name = n.to_vec();
                value = v.to_vec();
                add = false;
            } else if b & 0xe0 == 0x20 {
                if fields {
                    return Err(Error::TableSizeUpdate);
                }
                let n = read_int(block, &mut pos, 5)?;
                if n > self.max {
                    return Err(Error::TableSizeUpdate);
                }
                self.cur_max = n;
                self.evict(n);
                continue;
            } else {
                let (prefix, inc) = if b & 0x40 != 0 { (6, true) } else { (4, false) };
                let idx = read_int(block, &mut pos, prefix)?;
                name = if idx == 0 {
                    read_string(block, &mut pos)?
                } else {
                    self.lookup(idx)?.0.to_vec()
                };
                value = read_string(block, &mut pos)?;
                add = inc;
            }
            fields = true;
            total += name.len() + value.len() + 32;
            if total > MAX_LIST {
                return Err(Error::TooLarge);
            }
            if add {
                self.insert(name.clone(), value.clone());
            }
            out.push((name, value));
        }
        Ok(out)
    }
}

/// HPACK encoder: static-table references and non-Huffman literals only; never indexes.
pub struct Encoder {
    pending: Option<usize>,
}

impl Default for Encoder {
    fn default() -> Self {
        Self::new()
    }
}

impl Encoder {
    pub fn new() -> Self {
        Encoder { pending: None }
    }

    /// Peer's SETTINGS_HEADER_TABLE_SIZE; a size update is emitted at the next `encode`.
    pub fn set_max_table_size(&mut self, n: usize) {
        self.pending = Some(n);
    }

    /// Appends the encoded block to `out`. Header names must already be lowercase.
    pub fn encode(&mut self, headers: &[(&[u8], &[u8])], out: &mut Vec<u8>) {
        if let Some(n) = self.pending.take() {
            write_int(out, 0x20, 5, n);
        }
        for &(name, value) in headers {
            if let Some(i) = STATIC.iter().position(|&(n, v)| n == name && v == value) {
                write_int(out, 0x80, 7, i + 1);
                continue;
            }
            match STATIC.iter().position(|&(n, _)| n == name) {
                Some(i) => write_int(out, 0, 4, i + 1),
                None => {
                    write_int(out, 0, 4, 0);
                    write_int(out, 0, 7, name.len());
                    out.extend_from_slice(name);
                }
            }
            write_int(out, 0, 7, value.len());
            out.extend_from_slice(value);
        }
    }
}

