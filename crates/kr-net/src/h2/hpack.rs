        assert_eq!(huff_decode(&[0x18], &mut Vec::new()), Err(Error::BadHuffman));
        assert_eq!(huff_decode(&[0xff], &mut Vec::new()), Err(Error::BadHuffman));
        assert_eq!(huff_decode(&[0xff, 0xff, 0xff, 0xff], &mut Vec::new()), Err(Error::BadHuffman));
