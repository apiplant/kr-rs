#[derive(Clone, Copy, Debug)]
pub struct Point<const N: usize> {
    x: Uint<N>,
    y: Uint<N>,
    z: Uint<N>,
}

impl<const N: usize> Curve<N> {
    pub fn identity(&self) -> Point<N> {
        Point { x: Uint::ZERO, y: self.p.one(), z: Uint::ZERO }
    }

    pub fn generator(&self) -> Point<N> {
        Point { x: self.p.to_mont(&self.gx), y: self.p.to_mont(&self.gy), z: self.p.one() }
    }

    /// Complete addition (RCB16 Algorithm 4, a = -3). Also correct for doubling and identity.
    pub fn add(&self, s1: &Point<N>, o: &Point<N>) -> Point<N> {
        let p_ = &self.p;
        let b = p_.to_mont(&self.b);
        let (m, a, s) = (|x: &Uint<N>, y: &Uint<N>| p_.mul(x, y), |x: &Uint<N>, y: &Uint<N>| p_.add(x, y), |x: &Uint<N>, y: &Uint<N>| p_.sub(x, y));
        let (x1, y1, z1, x2, y2, z2) = (&s1.x, &s1.y, &s1.z, &o.x, &o.y, &o.z);
        let mut t0 = m(x1, x2);
        let mut t1 = m(y1, y2);
        let mut t2 = m(z1, z2);
        let mut t3 = a(x1, y1);
        let mut t4 = a(x2, y2);
        t3 = m(&t3, &t4);
        t4 = a(&t0, &t1);
        t3 = s(&t3, &t4);
        t4 = a(y1, z1);
        let mut x3 = a(y2, z2);
        t4 = m(&t4, &x3);
        x3 = a(&t1, &t2);
        t4 = s(&t4, &x3);
        x3 = a(x1, z1);
        let mut y3 = a(x2, z2);
        x3 = m(&x3, &y3);
        y3 = a(&t0, &t2);
        y3 = s(&x3, &y3);
        let mut z3 = m(&b, &t2);
        x3 = s(&y3, &z3);
        z3 = a(&x3, &x3);
        x3 = a(&x3, &z3);
        z3 = s(&t1, &x3);
        x3 = a(&t1, &x3);
        y3 = m(&b, &y3);
        t1 = a(&t2, &t2);
        t2 = a(&t1, &t2);
        y3 = s(&y3, &t2);
        y3 = s(&y3, &t0);
        t1 = a(&y3, &y3);
        y3 = a(&t1, &y3);
        t1 = a(&t0, &t0);
        t0 = a(&t1, &t0);
        t0 = s(&t0, &t2);
        t1 = m(&t4, &y3);
        t2 = m(&t0, &y3);
        y3 = m(&x3, &z3);
        y3 = a(&y3, &t2);
        x3 = m(&t3, &x3);
        x3 = s(&x3, &t1);
        z3 = m(&t4, &z3);
        t1 = m(&t3, &t0);
        z3 = a(&z3, &t1);
        Point { x: x3, y: y3, z: z3 }
    }

    fn select(a: &Point<N>, b: &Point<N>, choose: u64) -> Point<N> {
        Point { x: Uint::select(&a.x, &b.x, choose), y: Uint::select(&a.y, &b.y, choose), z: Uint::select(&a.z, &b.z, choose) }
    }

    /// k * pt, constant-time in k (k is a plain integer, any N-limb value).
    ///
    /// Fixed 4-bit window: a table of 0..15 * pt, then per nibble four doublings and one
    /// addition of the entry chosen by a full masked scan of the table (no secret-dependent
    /// index or branch). 256 doublings + 64 additions for P-256 instead of 256 + 256.
    pub fn mul(&self, pt: &Point<N>, k: &Uint<N>) -> Point<N> {
        let mut tbl = [self.identity(); 16];
        tbl[1] = *pt;
        for i in 2..16 {
            tbl[i] = self.add(&tbl[i - 1], pt);
        }
        let mut r = self.identity();
        for w in (0..16 * N).rev() {
            for _ in 0..4 {
                r = self.add(&r, &r);
            }
            let nib = (k.bit(4 * w) | k.bit(4 * w + 1) << 1 | k.bit(4 * w + 2) << 2 | k.bit(4 * w + 3) << 3) as u64;
            let mut sel = tbl[0];
            for (i, e) in tbl.iter().enumerate() {
                let d = nib ^ i as u64;
                // 1 iff d == 0, without branching.
                let eq = ((d | d.wrapping_neg()) >> 63) ^ 1;
                sel = Self::select(&sel, e, eq);
            }
            r = self.add(&r, &sel);
        }
        r
    }

    /// Affine (x, y) in plain form; None for the identity.
    pub fn to_affine(&self, pt: &Point<N>) -> Option<(Uint<N>, Uint<N>)> {
        if pt.z.is_zero() {
            return None;
        }
        let zi = self.p.inv(&pt.z);
        Some((self.p.from_mont(&self.p.mul(&pt.x, &zi)), self.p.from_mont(&self.p.mul(&pt.y, &zi))))
    }

    /// Decodes an uncompressed SEC1 point (0x04 || X || Y), checking range and the curve equation.
    pub fn decode(&self, b: &[u8]) -> Option<Point<N>> {
        let w = 8 * N;
        if b.len() != 1 + 2 * w || b[0] != 4 {
            return None;
        }
        let x = Uint::from_be_slice(&b[1..1 + w]);
        let y = Uint::from_be_slice(&b[1 + w..]);
        let p_ = &self.p;
        if !x.ct_lt(&p_.m) || !y.ct_lt(&p_.m) {
            return None;
        }
        let (xm, ym) = (p_.to_mont(&x), p_.to_mont(&y));
        // y^2 == x^3 - 3x + b
        let lhs = p_.mul(&ym, &ym);
        let x3 = p_.mul(&p_.mul(&xm, &xm), &xm);
        let three_x = p_.add(&p_.add(&xm, &xm), &xm);
        let rhs = p_.add(&p_.sub(&x3, &three_x), &p_.to_mont(&self.b));
        if lhs != rhs {
            return None;
        }
        Some(Point { x: xm, y: ym, z: p_.one() })
    }

    /// FIPS 186-4 bits2int: the leftmost bits of the digest, as many as the order has, mod n.
    pub fn digest_to_scalar(&self, digest: &[u8]) -> Uint<N> {
        let w = 8 * N;
        let mut buf = [0u8; 64];
        let take = digest.len().min(w);
        // Both supported orders have a full top limb, so byte truncation equals bit truncation.
        buf[w - take..w].copy_from_slice(&digest[..take]);
        self.n.reduce(&Uint::from_be_slice(&buf[..w]))
    }

    /// ECDSA verification of (r, s) (big-endian, any length up to 8N) over a digest.
    pub fn verify_digest(&self, pk: &[u8], digest: &[u8], r: &[u8], s: &[u8]) -> bool {
        let w = 8 * N;
        let Some(q) = self.decode(pk) else { return false };
        if r.len() > w || s.len() > w {
            return false;
        }
        let pad = |v: &[u8]| {
            let mut b = [0u8; 64];
            b[w - v.len()..w].copy_from_slice(v);
            Uint::<N>::from_be_slice(&b[..w])
        };
        let (r, s) = (pad(r), pad(s));
        let n = &self.n;
        if r.is_zero() || s.is_zero() || !r.ct_lt(&n.m) || !s.ct_lt(&n.m) {
            return false;
        }
        let e = self.digest_to_scalar(digest);
        let w_inv = n.inv(&n.to_mont(&s));
        let u1 = n.from_mont(&n.mul(&n.to_mont(&e), &w_inv));
        let u2 = n.from_mont(&n.mul(&n.to_mont(&r), &w_inv));
        let pt = self.add(&self.mul(&self.generator(), &u1), &self.mul(&q, &u2));
        match self.to_affine(&pt) {
            Some((x, _)) => n.reduce(&x) == r,
            None => false,
        }
    }
}

/// Strict DER `SEQUENCE { INTEGER r, INTEGER s }`: minimal, positive, short-form lengths.
/// Returns the magnitudes without the sign-padding byte.
pub fn sig_from_der(der: &[u8]) -> Option<(&[u8], &[u8])> {
    if der.len() < 8 || der[0] != 0x30 || der[1] >= 0x80 || der[1] as usize != der.len() - 2 {
        return None;
    }
    let mut rest = &der[2..];
    let mut take = || -> Option<&[u8]> {
        if rest.len() < 2 || rest[0] != 0x02 {
            return None;
        }
        let len = rest[1] as usize;
        if len == 0 || len > 67 || rest.len() < 2 + len {
            return None;
        }
        let v = &rest[2..2 + len];
        if v[0] & 0x80 != 0 || (len > 1 && v[0] == 0 && v[1] & 0x80 == 0) {
            return None; // negative or non-minimal
        }
        rest = &rest[2 + len..];
        Some(if v[0] == 0 && len > 1 { &v[1..] } else { v })
    };
    let r = take()?;
    let s = take()?;
    rest.is_empty().then_some((r, s))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check<const N: usize>(c: &Curve<N>) {
        let g = c.generator();
        let (x, y) = c.to_affine(&g).unwrap();
        let mut enc = [0u8; 97];
        let w = 8 * N;
        enc[0] = 4;
        x.write_be(&mut enc[1..1 + w]);
        y.write_be(&mut enc[1 + w..1 + 2 * w]);
        assert!(c.decode(&enc[..1 + 2 * w]).is_some());
        assert!(c.to_affine(&c.mul(&g, &c.n.m)).is_none()); // n * G = O
    }

    #[test]
    fn generators() {
        check(&P256);
        check(&P384);
    }
}
