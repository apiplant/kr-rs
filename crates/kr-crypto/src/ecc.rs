//! Short-Weierstrass curves with a = -3 (P-256, P-384), generic over the limb count.
//!
//! Projective coordinates with the complete addition formula of Renes, Costello and Batina
//! (2016, Algorithm 4, a = -3), so there are no special cases to branch on. Scalar
//! multiplication is a double-and-add-always ladder with constant-time selection. Field values
//! are in Montgomery form throughout.

use crate::bigint::{Modulus, Uint, P256_N, P256_P, P384_N, P384_P};

pub struct Curve<const N: usize> {
    pub p: Modulus<N>,
    pub n: Modulus<N>,
    /// Plain-form constants.
    pub b: Uint<N>,
    pub gx: Uint<N>,
    pub gy: Uint<N>,
}

